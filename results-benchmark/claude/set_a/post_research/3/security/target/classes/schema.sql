-- Schema for the authentication store. Portable between PostgreSQL 12+ and H2 2.x.
-- No credentials or seed users are defined here; use "AdminCli set-password".

CREATE TABLE IF NOT EXISTS app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_session (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_user_session_expires ON user_session (expires_at);

CREATE TABLE IF NOT EXISTS login_throttle (
    scope         VARCHAR(16) NOT NULL,
    scope_key     VARCHAR(64) NOT NULL,
    attempt_count INTEGER NOT NULL,
    window_start  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (scope, scope_key)
);

CREATE INDEX IF NOT EXISTS idx_login_throttle_window ON login_throttle (window_start);
