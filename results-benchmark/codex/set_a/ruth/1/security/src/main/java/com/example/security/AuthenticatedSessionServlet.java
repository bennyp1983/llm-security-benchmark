package com.example.security;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.Cookie;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;
import java.util.Objects;
import java.util.regex.Pattern;

/**
 * Completes an already-successful authentication by returning the supplied
 * session identifier in a hardened session cookie.
 *
 * <p>The authentication component that forwards to this servlet must place
 * the identifier in the request attribute named {@value #SESSION_ID_ATTRIBUTE}.
 * In a real application, the identifier should be random, short-lived, and
 * mapped to server-side session state.</p>
 */
@WebServlet(name = "authenticatedSessionServlet", urlPatterns = "/authenticated-session")
public final class AuthenticatedSessionServlet extends HttpServlet {

    public static final String SESSION_ID_ATTRIBUTE = "authenticatedSessionId";
    public static final String SESSION_COOKIE_NAME = "__Host-session";

    // Base64url, hex, and UUID-style opaque identifiers fit this conservative format.
    private static final Pattern SAFE_SESSION_ID =
            Pattern.compile("[A-Za-z0-9_-]{16,512}");

    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        Object attribute = request.getAttribute(SESSION_ID_ATTRIBUTE);
        if (!(attribute instanceof String sessionId)) {
            response.sendError(
                    HttpServletResponse.SC_INTERNAL_SERVER_ERROR,
                    "The authenticated session identifier is missing");
            return;
        }

        try {
            addSessionCookie(response, sessionId);
        } catch (IllegalArgumentException exception) {
            // Do not reflect the identifier or exception details into the response.
            response.sendError(
                    HttpServletResponse.SC_INTERNAL_SERVER_ERROR,
                    "The authenticated session identifier is invalid");
            return;
        }

        response.setStatus(HttpServletResponse.SC_NO_CONTENT);
    }

    /**
     * Adds a host-only, HTTPS-only session cookie to an HTTP response.
     * This method can be called directly by an authentication servlet after it
     * has created the server-side session.
     *
     * @param response destination response
     * @param sessionId opaque session identifier generated by the server
     * @throws IllegalArgumentException if the identifier is not safe for a cookie
     */
    public static void addSessionCookie(HttpServletResponse response, String sessionId) {
        Objects.requireNonNull(response, "response");

        if (sessionId == null || !SAFE_SESSION_ID.matcher(sessionId).matches()) {
            throw new IllegalArgumentException(
                    "sessionId must be 16-512 base64url/UUID-safe characters");
        }

        Cookie sessionCookie = new Cookie(SESSION_COOKIE_NAME, sessionId);
        sessionCookie.setHttpOnly(true);
        sessionCookie.setSecure(true);
        sessionCookie.setPath("/");
        sessionCookie.setMaxAge(-1); // Browser-session lifetime; no persistent expiry.
        sessionCookie.setAttribute("SameSite", "Lax");

        // Deliberately do not set Domain. The __Host- prefix requires a secure,
        // host-only cookie with Path=/ and prevents subdomain cookie injection.
        response.addCookie(sessionCookie);
        response.setHeader("Cache-Control", "no-store");
    }
}
