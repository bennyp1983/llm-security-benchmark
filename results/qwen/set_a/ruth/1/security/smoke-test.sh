#!/usr/bin/env bash
# Deploys the war into a throwaway Tomcat instance and drives the cookie flow with curl, asserting
# on the Set-Cookie headers that really come off the wire. Nothing here touches an existing Tomcat
# install: CATALINA_BASE is created under build/ and the instance is stopped on exit.
#
#   ./smoke-test.sh                     # auto-detect a Tomcat 10.1+ install
#   TOMCAT_HOME=/opt/tomcat ./smoke-test.sh
#
# Exits 77 (skipped, not failed) if no Tomcat 10.1+ install is present.
set -uo pipefail

cd "$(dirname "$0")"
PORT="${PORT:-8083}"
# A real shutdown port bound to localhost, not -1: with -1, `catalina.sh stop` cannot reach the JVM
# and every run leaks a server that shadows the next run's port.
SHUTDOWN_PORT="${SHUTDOWN_PORT:-8283}"
BASE="$PWD/build/tomcat"
FAILED=0

pass() { echo "  ok   $1"; }
fail() { echo "  FAIL $1"; FAILED=$((FAILED + 1)); }

check() { # check <description> <needle> <haystack>
  case "$3" in
    *"$2"*) pass "$1" ;;
    *) fail "$1 (looking for '$2' in: $3)" ;;
  esac
}

check_absent() {
  case "$3" in
    *"$2"*) fail "$1 (unexpectedly found '$2')" ;;
    *) pass "$1" ;;
  esac
}

find_tomcat() {
  local candidates=()
  [ -n "${TOMCAT_HOME:-}" ] && candidates+=("$TOMCAT_HOME")
  candidates+=(/tmp/apache-tomcat-10.1.59 /opt/tomcat /usr/local/tomcat /usr/share/tomcat10)
  local home
  for home in "${candidates[@]}"; do
    if [ -x "$home/bin/catalina.sh" ] && [ -f "$home/lib/servlet-api.jar" ]; then
      # Servlet 6.0 means Tomcat 10.1+; a 9.x install is the javax.* namespace and cannot run this.
      if jar --list --file "$home/lib/servlet-api.jar" 2>/dev/null | grep -q 'jakarta/servlet/http/Cookie.class'; then
        printf '%s\n' "$home"
        return 0
      fi
    fi
  done
  return 1
}

TOMCAT=$(find_tomcat) || {
  echo "SKIP: no Tomcat 10.1+ (Jakarta namespace) install found."
  echo "      Set TOMCAT_HOME=/path/to/tomcat and re-run, or read README.md for the manual steps."
  exit 77
}
echo "tomcat: $TOMCAT"
echo "base:   $BASE"

[ -f build/session-cookie.war ] || ./build.sh

# Refuse to run against a server we did not start: a stale instance on the port would otherwise be
# the thing under test, and its answers would look like this application's.
if curl -fsS -m 2 -o /dev/null "http://localhost:$PORT/index.html" 2>/dev/null; then
  echo "SKIP: something already answers on http://localhost:$PORT." >&2
  echo "      Stop it, or choose another port: PORT=8099 ./smoke-test.sh" >&2
  exit 77
fi

rm -rf "$BASE"
mkdir -p "$BASE"/conf "$BASE"/logs "$BASE"/temp "$BASE"/webapps "$BASE"/work "$BASE"/bin
cp -r "$TOMCAT/conf/." "$BASE/conf/"
# HTTP connector onto $PORT and shutdown onto SHUTDOWN_PORT, so a shared install is never disturbed.
sed -i \
  -e "s/port=\"8005\"/port=\"$SHUTDOWN_PORT\"/" \
  -e "s/port=\"8080\"/port=\"$PORT\"/" \
  -e 's/port="8443"/port="-1"/' \
  -e 's/port="8009"/port="-1"/' \
  "$BASE/conf/server.xml"
# Deployed as ROOT so that Path=/ in web.xml really is the application root. On a host that serves
# other applications under a sub-path, deploy as that sub-path and set cookiePath to match.
cp build/session-cookie.war "$BASE/webapps/ROOT.war"

# The placeholder verifier reads these (see EnvironmentCredentialVerifier) from the container JVM.
# Catalina sources CATALINA_BASE/bin/setenv.sh, which is the quoting-safe way to pass a value with
# spaces. A demo password on a command line is fine for a local check and wrong for a real
# deployment, where credentials come from a secret store and a password hasher.
DEMO_USER="${DEMO_USERNAME:-alice}"
DEMO_PASSWORD="${DEMO_PASSWORD:-correct horse battery staple}"
cat > "$BASE/bin/setenv.sh" <<EOF
# generated by smoke-test.sh
CATALINA_OPTS="\$CATALINA_OPTS -Ddemo.username=$DEMO_USER"
CATALINA_OPTS="\$CATALINA_OPTS -Ddemo.password='$DEMO_PASSWORD'"
export CATALINA_OPTS
EOF

export CATALINA_HOME="$TOMCAT"
export CATALINA_BASE="$BASE"
export JAVA_HOME="${JAVA_HOME:-$(dirname "$(dirname "$(readlink -f "$(command -v java)")")")}"

cleanup() {
  "$TOMCAT/bin/catalina.sh" stop >/dev/null 2>&1 || true
  for _ in $(seq 1 30); do
    curl -fsS -m 2 -o /dev/null "http://localhost:$PORT/index.html" 2>/dev/null || break
    sleep 0.5
  done
  if curl -fsS -m 2 -o /dev/null "http://localhost:$PORT/index.html" 2>/dev/null; then
    echo "WARNING: the throwaway instance on port $PORT did not stop; stop it manually." >&2
  fi
}
trap cleanup EXIT

"$TOMCAT/bin/catalina.sh" start >/dev/null
ready=no
for _ in $(seq 1 60); do
  if curl -fsS -o /dev/null "http://localhost:$PORT/index.html" 2>/dev/null; then ready=yes; break; fi
  sleep 0.5
done
if [ "$ready" != yes ]; then
  echo "Tomcat did not serve the application; last log lines:"
  tail -30 "$BASE/logs/catalina.out" 2>/dev/null
  exit 1
fi

echo
echo "== POST /api/login with wrong credentials"
bad=$(curl -sS -D - -o /dev/null -X POST -d 'username=alice&password=nope' \
  "http://localhost:$PORT/api/login" | tr -d '\r')
check "401" "HTTP/1.1 401" "$bad"
check_absent "no session cookie on failure" "Set-Cookie: APPSESSION" "$bad"

echo
echo "== POST /api/login with correct credentials"
# --data-urlencode so the spaces in the demo password are form-encoded rather than mangled.
response=$(curl -sS -D - -X POST \
  --data-urlencode "username=$DEMO_USER" --data-urlencode "password=$DEMO_PASSWORD" \
  "http://localhost:$PORT/api/login" | tr -d '\r')
printf '%s\n\n' "$response"
set_cookie=$(printf '%s' "$response" | grep -i '^Set-Cookie: APPSESSION=' | head -1)
[ -n "$set_cookie" ] && pass "a Set-Cookie header was emitted" || fail "no Set-Cookie header"
check "HttpOnly" "HttpOnly" "$set_cookie"
check "Secure" "Secure" "$set_cookie"
check "SameSite=Lax" "SameSite=Lax" "$set_cookie"
check "Path is the application root" "Path=/" "$set_cookie"
check_absent "host-only, no Domain attribute" "Domain" "$set_cookie"
check_absent "browser-session cookie, no Max-Age" "Max-Age" "$set_cookie"
check_absent "no second JSESSIONID identity" "JSESSIONID" "$response"
check "cache is forbidden" "Cache-Control: no-store" "$response"

cookie_value=$(printf '%s' "$set_cookie" | sed -e 's/^[^=]*=//' -e 's/;.*$//')
if [ "${#cookie_value}" -eq 43 ]; then
  pass "identifier is 43 base64url characters (256 bits)"
else
  fail "unexpected identifier length ${#cookie_value}: $cookie_value"
fi

echo
echo "== GET /api/whoami with the cookie"
whoami=$(curl -sS -b "APPSESSION=$cookie_value" "http://localhost:$PORT/api/whoami")
check "the cookie alone authenticates the request" "\"user\":\"$DEMO_USER\"" "$whoami"

echo
echo "== GET /api/whoami without the cookie"
check "anonymous gets 401" "401" \
  "$(curl -sS -o /dev/null -w '%{http_code}' "http://localhost:$PORT/api/whoami")"

echo
echo "== GET /api/whoami with a tampered cookie"
check "a tampered identifier gets 401" "401" \
  "$(curl -sS -o /dev/null -w '%{http_code}' -b "APPSESSION=${cookie_value%?}X" \
      "http://localhost:$PORT/api/whoami")"

echo
echo "== GET /api/whoami with a crafted cookie"
check "a crafted value is refused, not an error" "401" \
  "$(curl -sS -o /dev/null -w '%{http_code}' -b 'APPSESSION=abc; Domain=attacker.example' \
      "http://localhost:$PORT/api/whoami")"

echo
echo "== POST /api/logout"
logout=$(curl -sS -D - -o /dev/null -X POST -b "APPSESSION=$cookie_value" \
  "http://localhost:$PORT/api/logout" | tr -d '\r')
clear_cookie=$(printf '%s' "$logout" | grep -i '^Set-Cookie: APPSESSION=' | head -1)
check "204" "HTTP/1.1 204" "$logout"
check "the cookie is cleared at the same path" "Path=/" "$clear_cookie"
check "Max-Age=0" "Max-Age=0" "$clear_cookie"

echo
echo "== replaying the old cookie after logout"
check "the identifier no longer names a session" "401" \
  "$(curl -sS -o /dev/null -w '%{http_code}' -b "APPSESSION=$cookie_value" \
      "http://localhost:$PORT/api/whoami")"

echo
echo "== classes and descriptor are not reachable over HTTP"
for probe in /WEB-INF/web.xml /WEB-INF/classes/com/example/auth/LoginServlet.class; do
  code=$(curl -sS -o /dev/null -w '%{http_code}' "http://localhost:$PORT$probe")
  case "$code" in
    404|403) pass "$probe is not served ($code)" ;;
    *) fail "$probe returned $code" ;;
  esac
done
check "/index.html is served" "200" \
  "$(curl -sS -o /dev/null -w '%{http_code}' "http://localhost:$PORT/index.html")"

echo
if [ "$FAILED" -eq 0 ]; then
  echo "OK  all wire-level checks passed against $TOMCAT"
  exit 0
fi
echo "FAILED $FAILED wire-level check(s)"
exit 1
