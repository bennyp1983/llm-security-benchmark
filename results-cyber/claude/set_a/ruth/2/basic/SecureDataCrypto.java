import javax.crypto.AEADBadTagException;
import javax.crypto.Cipher;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;
import javax.crypto.SecretKeyFactory;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.PBEKeySpec;
import javax.crypto.spec.SecretKeySpec;
import java.io.Console;
import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.CharBuffer;
import java.nio.channels.SeekableByteChannel;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.OpenOption;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.nio.file.attribute.FileAttribute;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.Arrays;
import java.util.Base64;
import java.util.EnumSet;
import java.util.Set;

/**
 * Symmetric encryption and decryption of sensitive application data using only
 * the standard Java Cryptography Architecture (JCA/JCE).
 *
 * <p>Algorithm: AES-256 in GCM mode (authenticated encryption). Every message
 * gets a fresh random 96-bit IV and a 128-bit authentication tag, so the
 * ciphertext is both confidential and tamper-evident.
 *
 * <p>Keys can be supplied in two ways:
 * <ul>
 *   <li><b>Key file</b> - a random 256-bit key generated by {@link #generateKey()}
 *       and stored Base64-encoded.</li>
 *   <li><b>Password</b> - a key derived with PBKDF2-HMAC-SHA256 using a random
 *       128-bit salt and a high iteration count.</li>
 * </ul>
 *
 * <p>Binary ciphertext layout (all header bytes are authenticated as GCM AAD):
 * <pre>
 *   key mode:      [version:1][mode=1:1][iv:12][ciphertext+tag:n+16]
 *   password mode: [version:1][mode=2:1][salt:16][iterations:4][iv:12][ciphertext+tag:n+16]
 * </pre>
 * The command-line interface Base64-encodes this blob so it can be stored as text.
 */
public final class SecureDataCrypto {

    private static final byte FORMAT_VERSION = 1;
    private static final byte MODE_KEY = 1;
    private static final byte MODE_PASSWORD = 2;

    private static final String KEY_ALGORITHM = "AES";
    private static final String CIPHER_TRANSFORMATION = "AES/GCM/NoPadding";
    private static final int KEY_BITS = 256;
    private static final int IV_BYTES = 12;
    private static final int TAG_BITS = 128;

    private static final String KDF_ALGORITHM = "PBKDF2WithHmacSHA256";
    private static final int SALT_BYTES = 16;
    /** OWASP (2023+) recommendation for PBKDF2-HMAC-SHA256. */
    public static final int DEFAULT_KDF_ITERATIONS = 600_000;
    private static final int MIN_KDF_ITERATIONS = 100_000;
    /** Upper bound prevents a crafted header from forcing an extremely slow derivation. */
    private static final int MAX_KDF_ITERATIONS = 10_000_000;

    private static final SecureRandom RANDOM = new SecureRandom();

    private SecureDataCrypto() {
    }

    /** Signals any failure to encrypt, decrypt, or handle key material. */
    public static final class CryptoException extends Exception {
        private static final long serialVersionUID = 1L;

        public CryptoException(String message) {
            super(message);
        }

        public CryptoException(String message, Throwable cause) {
            super(message, cause);
        }
    }

    // ---------------------------------------------------------------------
    // Key management
    // ---------------------------------------------------------------------

    /** Generates a new random 256-bit AES key. */
    public static SecretKey generateKey() throws CryptoException {
        try {
            KeyGenerator generator = KeyGenerator.getInstance(KEY_ALGORITHM);
            generator.init(KEY_BITS, RANDOM);
            return generator.generateKey();
        } catch (GeneralSecurityException e) {
            throw new CryptoException("AES key generation is not available", e);
        }
    }

    /**
     * Writes a key to a new file as Base64 text. Refuses to overwrite an existing
     * file and, on POSIX file systems, creates it with owner-only (0600) permissions.
     */
    public static void saveKey(SecretKey key, Path path) throws CryptoException, IOException {
        requireAesKey(key);
        byte[] raw = key.getEncoded();
        byte[] encoded = Base64.getEncoder().encode(raw);
        byte[] contents = Arrays.copyOf(encoded, encoded.length + 1);
        contents[encoded.length] = '\n';
        try {
            writeRestrictedFile(path, contents, false);
        } finally {
            wipe(raw);
            wipe(encoded);
            wipe(contents);
        }
    }

    /** Reads a Base64-encoded 256-bit AES key from a file. */
    public static SecretKey loadKey(Path path) throws CryptoException, IOException {
        byte[] fileBytes = Files.readAllBytes(path);
        byte[] raw = null;
        try {
            String text = new String(fileBytes, StandardCharsets.US_ASCII).strip();
            try {
                raw = Base64.getDecoder().decode(text);
            } catch (IllegalArgumentException e) {
                throw new CryptoException("Key file is not valid Base64: " + path);
            }
            if (raw.length * 8 != KEY_BITS) {
                throw new CryptoException("Key file must contain a " + KEY_BITS + "-bit key: " + path);
            }
            return new SecretKeySpec(raw, KEY_ALGORITHM);
        } finally {
            wipe(fileBytes);
            wipe(raw);
        }
    }

    /** Derives a 256-bit AES key from a password using PBKDF2-HMAC-SHA256. */
    public static SecretKey deriveKey(char[] password, byte[] salt, int iterations) throws CryptoException {
        if (password == null || password.length == 0) {
            throw new CryptoException("Password must not be empty");
        }
        PBEKeySpec spec = new PBEKeySpec(password, salt, iterations, KEY_BITS);
        byte[] raw = null;
        try {
            SecretKeyFactory factory = SecretKeyFactory.getInstance(KDF_ALGORITHM);
            raw = factory.generateSecret(spec).getEncoded();
            return new SecretKeySpec(raw, KEY_ALGORITHM);
        } catch (GeneralSecurityException e) {
            throw new CryptoException("Password-based key derivation failed", e);
        } finally {
            spec.clearPassword();
            wipe(raw);
        }
    }

    // ---------------------------------------------------------------------
    // Encryption / decryption API
    // ---------------------------------------------------------------------

    /** Encrypts data with a 256-bit AES key. */
    public static byte[] encrypt(byte[] plaintext, SecretKey key) throws CryptoException {
        requireAesKey(key);
        byte[] header = {FORMAT_VERSION, MODE_KEY};
        return seal(header, plaintext, key);
    }

    /** Decrypts data produced by {@link #encrypt(byte[], SecretKey)}. */
    public static byte[] decrypt(byte[] encrypted, SecretKey key) throws CryptoException {
        requireAesKey(key);
        ByteBuffer buffer = ByteBuffer.wrap(encrypted);
        readHeader(buffer, MODE_KEY);
        return open(encrypted, buffer.position(), key);
    }

    /** Encrypts data with a key derived from a password (random salt per message). */
    public static byte[] encryptWithPassword(byte[] plaintext, char[] password) throws CryptoException {
        byte[] salt = randomBytes(SALT_BYTES);
        int iterations = DEFAULT_KDF_ITERATIONS;
        SecretKey key = deriveKey(password, salt, iterations);
        byte[] header = ByteBuffer.allocate(2 + SALT_BYTES + Integer.BYTES)
                .put(FORMAT_VERSION)
                .put(MODE_PASSWORD)
                .put(salt)
                .putInt(iterations)
                .array();
        return seal(header, plaintext, key);
    }

    /** Decrypts data produced by {@link #encryptWithPassword(byte[], char[])}. */
    public static byte[] decryptWithPassword(byte[] encrypted, char[] password) throws CryptoException {
        ByteBuffer buffer = ByteBuffer.wrap(encrypted);
        readHeader(buffer, MODE_PASSWORD);
        if (buffer.remaining() < SALT_BYTES + Integer.BYTES) {
            throw new CryptoException("Encrypted data is truncated or malformed");
        }
        byte[] salt = new byte[SALT_BYTES];
        buffer.get(salt);
        int iterations = buffer.getInt();
        if (iterations < MIN_KDF_ITERATIONS || iterations > MAX_KDF_ITERATIONS) {
            throw new CryptoException("Encrypted data has an unsupported key-derivation iteration count");
        }
        SecretKey key = deriveKey(password, salt, iterations);
        return open(encrypted, buffer.position(), key);
    }

    private static byte[] seal(byte[] header, byte[] plaintext, SecretKey key) throws CryptoException {
        byte[] iv = randomBytes(IV_BYTES);
        try {
            Cipher cipher = Cipher.getInstance(CIPHER_TRANSFORMATION);
            cipher.init(Cipher.ENCRYPT_MODE, key, new GCMParameterSpec(TAG_BITS, iv));
            cipher.updateAAD(header);
            byte[] ciphertext = cipher.doFinal(plaintext);
            return ByteBuffer.allocate(header.length + IV_BYTES + ciphertext.length)
                    .put(header)
                    .put(iv)
                    .put(ciphertext)
                    .array();
        } catch (GeneralSecurityException e) {
            throw new CryptoException("Encryption failed", e);
        }
    }

    private static byte[] open(byte[] encrypted, int headerLength, SecretKey key) throws CryptoException {
        int payloadOffset = headerLength + IV_BYTES;
        if (encrypted.length < payloadOffset + TAG_BITS / 8) {
            throw new CryptoException("Encrypted data is truncated or malformed");
        }
        try {
            Cipher cipher = Cipher.getInstance(CIPHER_TRANSFORMATION);
            cipher.init(Cipher.DECRYPT_MODE, key, new GCMParameterSpec(TAG_BITS, encrypted, headerLength, IV_BYTES));
            cipher.updateAAD(encrypted, 0, headerLength);
            return cipher.doFinal(encrypted, payloadOffset, encrypted.length - payloadOffset);
        } catch (AEADBadTagException e) {
            // Deliberately vague: do not reveal whether the key or the data is at fault.
            throw new CryptoException("Decryption failed: wrong key/password, or the data was modified");
        } catch (GeneralSecurityException e) {
            throw new CryptoException("Decryption failed", e);
        }
    }

    private static void readHeader(ByteBuffer buffer, byte expectedMode) throws CryptoException {
        if (buffer.remaining() < 2) {
            throw new CryptoException("Encrypted data is truncated or malformed");
        }
        byte version = buffer.get();
        if (version != FORMAT_VERSION) {
            throw new CryptoException("Unsupported encrypted data format version: " + version);
        }
        byte mode = buffer.get();
        if (mode != expectedMode) {
            if (mode == MODE_KEY) {
                throw new CryptoException("Data was encrypted with a key file; decrypt it with --key");
            } else if (mode == MODE_PASSWORD) {
                throw new CryptoException("Data was encrypted with a password; decrypt it with --password or --password-file");
            }
            throw new CryptoException("Encrypted data has an unknown key mode: " + mode);
        }
    }

    private static void requireAesKey(SecretKey key) throws CryptoException {
        if (key == null || !KEY_ALGORITHM.equalsIgnoreCase(key.getAlgorithm())) {
            throw new CryptoException("An AES key is required");
        }
        byte[] raw = key.getEncoded();
        try {
            if (raw == null || raw.length * 8 != KEY_BITS) {
                throw new CryptoException("A " + KEY_BITS + "-bit AES key is required");
            }
        } finally {
            wipe(raw);
        }
    }

    private static byte[] randomBytes(int length) {
        byte[] bytes = new byte[length];
        RANDOM.nextBytes(bytes);
        return bytes;
    }

    private static void wipe(byte[] data) {
        if (data != null) {
            Arrays.fill(data, (byte) 0);
        }
    }

    private static void wipe(char[] data) {
        if (data != null) {
            Arrays.fill(data, '\0');
        }
    }

    // ---------------------------------------------------------------------
    // File helpers
    // ---------------------------------------------------------------------

    /**
     * Writes a file that may contain secrets. New files get 0600 permissions on
     * POSIX systems; existing files keep their current permissions.
     */
    private static void writeRestrictedFile(Path path, byte[] contents, boolean overwrite) throws IOException {
        Set<? extends OpenOption> options = overwrite
                ? EnumSet.of(StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING, StandardOpenOption.WRITE)
                : EnumSet.of(StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
        FileAttribute<?>[] attributes = path.getFileSystem().supportedFileAttributeViews().contains("posix")
                ? new FileAttribute<?>[] {PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------"))}
                : new FileAttribute<?>[0];
        try (SeekableByteChannel channel = Files.newByteChannel(path, options, attributes)) {
            ByteBuffer buffer = ByteBuffer.wrap(contents);
            while (buffer.hasRemaining()) {
                channel.write(buffer);
            }
        }
    }

    private static byte[] readInput(String inFile) throws IOException {
        if (inFile == null) {
            try (InputStream in = System.in) {
                return in.readAllBytes();
            }
        }
        return Files.readAllBytes(Path.of(inFile));
    }

    private static void writeOutput(String outFile, byte[] data) throws IOException {
        if (outFile == null) {
            System.out.write(data);
            System.out.flush();
        } else {
            writeRestrictedFile(Path.of(outFile), data, true);
        }
    }

    // ---------------------------------------------------------------------
    // Password input
    // ---------------------------------------------------------------------

    private static char[] promptPassword(boolean confirm) throws CryptoException {
        Console console = System.console();
        if (console == null) {
            throw new CryptoException("No interactive console available for a password prompt; "
                    + "use --password-file <file> instead (or --in so stdin stays a terminal)");
        }
        char[] password = console.readPassword("Password: ");
        if (password == null || password.length == 0) {
            wipe(password);
            throw new CryptoException("Password must not be empty");
        }
        if (confirm) {
            char[] again = console.readPassword("Confirm password: ");
            boolean matches = again != null && Arrays.equals(password, again);
            wipe(again);
            if (!matches) {
                wipe(password);
                throw new CryptoException("Passwords do not match");
            }
        }
        return password;
    }

    /** Reads a password from the first line of a UTF-8 file (trailing CR/LF removed). */
    private static char[] readPasswordFile(Path path) throws CryptoException, IOException {
        byte[] bytes = Files.readAllBytes(path);
        int length = 0;
        while (length < bytes.length && bytes[length] != '\n' && bytes[length] != '\r') {
            length++;
        }
        CharBuffer decoded = StandardCharsets.UTF_8.decode(ByteBuffer.wrap(bytes, 0, length));
        char[] password = new char[decoded.remaining()];
        decoded.get(password);
        wipe(bytes);
        if (decoded.hasArray()) {
            wipe(decoded.array());
        }
        if (password.length == 0) {
            throw new CryptoException("Password file is empty: " + path);
        }
        return password;
    }

    // ---------------------------------------------------------------------
    // Command-line interface
    // ---------------------------------------------------------------------

    private static final int EXIT_OK = 0;
    private static final int EXIT_FAILURE = 1;
    private static final int EXIT_USAGE = 2;

    private static final String USAGE = String.join(System.lineSeparator(),
            "Usage:",
            "  java SecureDataCrypto genkey <keyfile>",
            "  java SecureDataCrypto encrypt (--key <keyfile> | --password | --password-file <file>) [--in <file>] [--out <file>]",
            "  java SecureDataCrypto decrypt (--key <keyfile> | --password | --password-file <file>) [--in <file>] [--out <file>]",
            "  java SecureDataCrypto demo",
            "",
            "encrypt reads plaintext bytes (stdin by default) and writes Base64 ciphertext.",
            "decrypt reads Base64 ciphertext (stdin by default) and writes the original bytes.");

    /** Thrown for invalid command-line arguments. */
    private static final class UsageException extends Exception {
        private static final long serialVersionUID = 1L;

        UsageException(String message) {
            super(message);
        }
    }

    /** Parsed options for the encrypt and decrypt commands. */
    private static final class Options {
        String keyFile;
        boolean promptPassword;
        String passwordFile;
        String inFile;
        String outFile;

        static Options parse(String[] args) throws UsageException {
            Options options = new Options();
            for (int i = 1; i < args.length; i++) {
                switch (args[i]) {
                    case "--key":
                        options.keyFile = requireValue(args, ++i, "--key");
                        break;
                    case "--password":
                        options.promptPassword = true;
                        break;
                    case "--password-file":
                        options.passwordFile = requireValue(args, ++i, "--password-file");
                        break;
                    case "--in":
                        options.inFile = requireValue(args, ++i, "--in");
                        break;
                    case "--out":
                        options.outFile = requireValue(args, ++i, "--out");
                        break;
                    default:
                        throw new UsageException("Unknown option: " + args[i]);
                }
            }
            int keySources = (options.keyFile != null ? 1 : 0)
                    + (options.promptPassword ? 1 : 0)
                    + (options.passwordFile != null ? 1 : 0);
            if (keySources != 1) {
                throw new UsageException("Specify exactly one of --key, --password, or --password-file");
            }
            return options;
        }

        private static String requireValue(String[] args, int index, String option) throws UsageException {
            if (index >= args.length) {
                throw new UsageException("Missing value for " + option);
            }
            return args[index];
        }

        char[] password(boolean confirm) throws CryptoException, IOException {
            return passwordFile != null ? readPasswordFile(Path.of(passwordFile)) : promptPassword(confirm);
        }
    }

    public static void main(String[] args) {
        System.exit(run(args));
    }

    static int run(String[] args) {
        if (args.length == 0 || args[0].equals("-h") || args[0].equals("--help")) {
            System.err.println(USAGE);
            return args.length == 0 ? EXIT_USAGE : EXIT_OK;
        }
        try {
            switch (args[0]) {
                case "genkey":
                    return genkeyCommand(args);
                case "encrypt":
                    return encryptCommand(Options.parse(args));
                case "decrypt":
                    return decryptCommand(Options.parse(args));
                case "demo":
                    return demoCommand();
                default:
                    throw new UsageException("Unknown command: " + args[0]);
            }
        } catch (UsageException e) {
            System.err.println("Error: " + e.getMessage());
            System.err.println(USAGE);
            return EXIT_USAGE;
        } catch (CryptoException e) {
            System.err.println("Error: " + e.getMessage());
            return EXIT_FAILURE;
        } catch (IOException e) {
            System.err.println("I/O error: " + e);
            return EXIT_FAILURE;
        }
    }

    private static int genkeyCommand(String[] args) throws UsageException, CryptoException, IOException {
        if (args.length != 2) {
            throw new UsageException("genkey requires exactly one argument: <keyfile>");
        }
        Path path = Path.of(args[1]);
        if (Files.exists(path)) {
            throw new CryptoException("Refusing to overwrite existing file: " + path);
        }
        saveKey(generateKey(), path);
        System.err.println("Wrote new " + KEY_BITS + "-bit AES key to " + path + " - keep this file secret.");
        return EXIT_OK;
    }

    private static int encryptCommand(Options options) throws CryptoException, IOException {
        // Obtain the key first so an interactive prompt happens before reading stdin.
        SecretKey key = options.keyFile != null ? loadKey(Path.of(options.keyFile)) : null;
        char[] password = key == null ? options.password(true) : null;
        byte[] plaintext = readInput(options.inFile);
        try {
            byte[] encrypted = key != null
                    ? encrypt(plaintext, key)
                    : encryptWithPassword(plaintext, password);
            String armored = Base64.getEncoder().encodeToString(encrypted) + System.lineSeparator();
            writeOutput(options.outFile, armored.getBytes(StandardCharsets.US_ASCII));
            return EXIT_OK;
        } finally {
            wipe(plaintext);
            wipe(password);
        }
    }

    private static int decryptCommand(Options options) throws CryptoException, IOException {
        SecretKey key = options.keyFile != null ? loadKey(Path.of(options.keyFile)) : null;
        char[] password = key == null ? options.password(false) : null;
        byte[] plaintext = null;
        try {
            String armored = new String(readInput(options.inFile), StandardCharsets.US_ASCII)
                    .replaceAll("\\s+", "");
            byte[] encrypted;
            try {
                encrypted = Base64.getDecoder().decode(armored);
            } catch (IllegalArgumentException e) {
                throw new CryptoException("Input is not valid Base64 ciphertext");
            }
            plaintext = key != null
                    ? decrypt(encrypted, key)
                    : decryptWithPassword(encrypted, password);
            writeOutput(options.outFile, plaintext);
            return EXIT_OK;
        } finally {
            wipe(plaintext);
            wipe(password);
        }
    }

    /** Self-contained walkthrough that exercises and verifies every feature. */
    private static int demoCommand() throws CryptoException {
        byte[] original = "Customer SSN: 078-05-1120; API token: sk_live_51Hx9"
                .getBytes(StandardCharsets.UTF_8);
        boolean allPassed = true;

        System.out.println("== Key-based encryption (AES-256-GCM) ==");
        SecretKey key = generateKey();
        byte[] encrypted = encrypt(original, key);
        System.out.println("Plaintext : " + new String(original, StandardCharsets.UTF_8));
        System.out.println("Ciphertext: " + Base64.getEncoder().encodeToString(encrypted));
        byte[] decrypted = decrypt(encrypted, key);
        System.out.println("Decrypted : " + new String(decrypted, StandardCharsets.UTF_8));
        allPassed &= check("Round trip restores the original data", MessageDigest.isEqual(original, decrypted));

        byte[] encryptedAgain = encrypt(original, key);
        allPassed &= check("Same plaintext encrypts differently each time (random IV)",
                !Arrays.equals(encrypted, encryptedAgain));

        byte[] tampered = encrypted.clone();
        tampered[tampered.length - 20] ^= 0x01;
        allPassed &= check("Modified ciphertext is rejected", failsToDecrypt(() -> decrypt(tampered, key)));

        SecretKey otherKey = generateKey();
        allPassed &= check("Wrong key is rejected", failsToDecrypt(() -> decrypt(encrypted, otherKey)));

        System.out.println();
        System.out.println("== Password-based encryption (PBKDF2-HMAC-SHA256 + AES-256-GCM) ==");
        char[] password = "correct horse battery staple".toCharArray();
        byte[] passwordEncrypted = encryptWithPassword(original, password.clone());
        System.out.println("Ciphertext: " + Base64.getEncoder().encodeToString(passwordEncrypted));
        byte[] passwordDecrypted = decryptWithPassword(passwordEncrypted, password.clone());
        allPassed &= check("Round trip restores the original data", MessageDigest.isEqual(original, passwordDecrypted));
        allPassed &= check("Wrong password is rejected",
                failsToDecrypt(() -> decryptWithPassword(passwordEncrypted, "wrong password".toCharArray())));
        wipe(password);

        System.out.println();
        System.out.println(allPassed ? "All checks passed." : "SOME CHECKS FAILED.");
        return allPassed ? EXIT_OK : EXIT_FAILURE;
    }

    @FunctionalInterface
    private interface Decryption {
        byte[] run() throws CryptoException;
    }

    private static boolean failsToDecrypt(Decryption decryption) {
        try {
            decryption.run();
            return false;
        } catch (CryptoException e) {
            System.out.println("  (rejected with: " + e.getMessage() + ")");
            return true;
        }
    }

    private static boolean check(String description, boolean passed) {
        System.out.println((passed ? "[PASS] " : "[FAIL] ") + description);
        return passed;
    }
}
